// The live definition of every function, trigger and policy after all migrations, read from a database the
// migrations built. About a quarter of the migrations patch functions by text (pg_get_functiondef + replace),
// so the last `create or replace` in a file is often not what runs. This prints what does.
//
// Usage: npm run schema:dump [-- --out FILE] [-- --function NAME]
//   Runs on the operator test machine through scripts/run-on-node.mjs (the working tree, uncommitted changes
//   included) and writes the dump to FILE (default: qorpera-live-schema.sql in the temporary directory).
//   --function NAME also prints that function's definitions (every overload; NAME may carry a schema).
//   --here runs against a local Docker instead and prints the dump (what the test machine runs).
// The dump is generated, never committed: every SQL change would conflict on it.
import { spawn } from "node:child_process";
import { writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { HostedDbCluster, MIGRATED, migrationNames } from "./test-hosted-db-cluster.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const BEGIN = "=== qorpera live schema begin ===";
const END = "=== qorpera live schema end ===";

/** Deterministic: byte order ("C" collation) and schema-qualified names (empty search_path). Objects that
 * belong to an extension are left out. */
export const DUMP_SQL = `set search_path = '';
with objects as (
	select 1 as kind, n.nspname as schema_name, p.proname as object_name, pg_catalog.pg_get_function_identity_arguments(p.oid) as detail,
		pg_catalog.format(E'-- @live function %s.%s(%s)\\n%s;\\n', n.nspname, p.proname, pg_catalog.pg_get_function_identity_arguments(p.oid),
			pg_catalog.rtrim(pg_catalog.pg_get_functiondef(p.oid), E'\\n')) as body
	from pg_catalog.pg_proc p join pg_catalog.pg_namespace n on n.oid = p.pronamespace
	where p.prokind in ('f', 'p', 'w')
		and n.nspname not in ('pg_catalog', 'information_schema') and n.nspname !~ '^pg_(toast|temp)'
		and not exists (select 1 from pg_catalog.pg_depend d
			where d.classid = 'pg_catalog.pg_proc'::pg_catalog.regclass and d.objid = p.oid and d.deptype = 'e')
	union all
	select 2, n.nspname, c.relname, t.tgname,
		pg_catalog.format(E'-- @live trigger %s on %s.%s\\n%s;\\n', t.tgname, n.nspname, c.relname, pg_catalog.pg_get_triggerdef(t.oid, true))
	from pg_catalog.pg_trigger t join pg_catalog.pg_class c on c.oid = t.tgrelid join pg_catalog.pg_namespace n on n.oid = c.relnamespace
	where not t.tgisinternal and n.nspname not in ('pg_catalog', 'information_schema')
		and not exists (select 1 from pg_catalog.pg_depend d
			where d.classid = 'pg_catalog.pg_class'::pg_catalog.regclass and d.objid = c.oid and d.deptype = 'e')
	union all
	select 3, p.schemaname, p.tablename, p.policyname,
		pg_catalog.format(E'-- @live policy %s on %s.%s\\ncreate policy %I on %I.%I as %s for %s to %s%s%s;\\n',
			p.policyname, p.schemaname, p.tablename, p.policyname, p.schemaname, p.tablename, p.permissive, p.cmd,
			pg_catalog.array_to_string(p.roles, ', '),
			coalesce(E'\\n\\tusing (' || p.qual || ')', ''), coalesce(E'\\n\\twith check (' || p.with_check || ')', ''))
	from pg_catalog.pg_policies p
)
select pg_catalog.string_agg(body, E'\\n' order by kind, schema_name collate "C", object_name collate "C", detail collate "C")
from objects;`;

/** The definitions of function `name` (`schema.name`, or `public.name`) in a dump. */
export function functionDefinitions(dump, name) {
	const qualified = name.includes(".") ? name : `public.${name}`;
	return dump
		.split(/\n(?=-- @live (?:function|trigger|policy) )/)
		.filter((block) => block.startsWith(`-- @live function ${qualified}(`))
		.join("\n");
}

function parseArgs(argv) {
	const options = { here: false, out: join(tmpdir(), "qorpera-live-schema.sql"), function: null };
	for (let i = 0; i < argv.length; i++) {
		if (argv[i] === "--here") options.here = true;
		else if (argv[i] === "--out" && argv[i + 1]) options.out = resolve(argv[++i]);
		else if (argv[i] === "--function" && /^([a-z_][a-z0-9_]*\.)?[a-z_][a-z0-9_]*$/.test(argv[i + 1] ?? "")) options.function = argv[++i];
		else throw new Error("Usage: node scripts/dump-live-schema.mjs [--out FILE] [--function NAME] [--here]");
	}
	return options;
}

async function dumpHere() {
	const cluster = await HostedDbCluster.start();
	try {
		const migrations = migrationNames();
		cluster.build({ progress: false });
		const body = cluster.psql(MIGRATED, DUMP_SQL, ["-qAt"]).replace(/\n+$/, "");
		return `-- Live functions, triggers and policies after ${migrations.length} migrations (last: ${migrations.at(-1)}).\n-- Generated by scripts/dump-live-schema.mjs; not committed.\n\n${body}\n`;
	} finally {
		cluster.stop();
	}
}

/** Runs `--here` on the test machine and returns the dump from its output. */
function dumpOnTestMachine() {
	return new Promise((resolvePromise, reject) => {
		const child = spawn(
			process.execPath,
			["scripts/run-on-node.mjs", "--no-install", "--", "node", "scripts/dump-live-schema.mjs", "--here"],
			{ cwd: root, stdio: ["ignore", "pipe", "inherit"] },
		);
		const lines = [];
		let inside = false;
		let dump = null;
		let pending = "";
		child.stdout.setEncoding("utf8");
		child.stdout.on("data", (chunk) => {
			pending += chunk;
			const complete = pending.split("\n");
			pending = complete.pop();
			for (const line of complete) {
				if (line === BEGIN) inside = true;
				else if (line === END) {
					inside = false;
					dump = `${lines.join("\n")}\n`;
				} else if (inside) lines.push(line);
				else process.stderr.write(`${line}\n`);
			}
		});
		child.on("error", reject);
		child.on("close", (code) => {
			if (code === 0 && dump !== null) resolvePromise(dump);
			else reject(new Error(`The test machine run failed (exit ${code})${dump === null ? " and printed no dump" : ""}`));
		});
	});
}

async function main() {
	const options = parseArgs(process.argv.slice(2));
	if (options.here && process.argv.slice(2).length === 1) {
		const dump = await dumpHere();
		process.stdout.write(`${BEGIN}\n${dump}${END}\n`);
		return;
	}
	const dump = options.here ? await dumpHere() : await dumpOnTestMachine();
	writeFileSync(options.out, dump);
	process.stderr.write(`Live schema written to ${options.out} (${dump.length} bytes)\n`);
	if (options.function) {
		const definitions = functionDefinitions(dump, options.function);
		if (!definitions) throw new Error(`No function ${options.function} in the live schema`);
		process.stdout.write(definitions);
	}
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
	main().catch((error) => {
		console.error(`dump-live-schema: ${error.message}`);
		process.exit(1);
	});
}
