#!/usr/bin/env node
// Writes the files of the interface app kits (deploy/first-node/RUNTIME-INTERFACE-APPS.md §3a and §3b) into the
// runtime as text: packages/runtime/kits/explainer/engine.js, which `save_app` writes into an app's folder, becomes
// packages/runtime/src/cloud-app-kit-explainer-engine.generated.ts, the voice-*.cjs scripts beside it, which the
// runtime runs on a company machine, become cloud-app-kit-explainer-voice.generated.ts, and the engines of the data
// kits (packages/runtime/kits/{model,board,path,object}/engine.js) and each one's guide for agents (KIT.md beside it,
// which save_app's schema carries) become cloud-app-kit-engines.generated.ts. Run it after changing one:
//   npm run generate:app-kits
// packages/runtime/test/cloud-app-kit-explainer.test.ts and cloud-app-kits.test.ts fail while source and text differ.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const EXPLAINER_ENGINE_SOURCE = "packages/runtime/kits/explainer/engine.js";
export const EXPLAINER_ENGINE_GENERATED = "packages/runtime/src/cloud-app-kit-explainer-engine.generated.ts";
/** The scripts a company machine runs to give an explainer its voice, by the name the runtime holds each under. */
export const EXPLAINER_VOICE_SOURCES = {
	EXPLAINER_VOICE_CAPTIONS_CJS: "packages/runtime/kits/explainer/voice-captions.cjs",
	EXPLAINER_VOICE_PEER_CJS: "packages/runtime/kits/explainer/voice-peer.cjs",
	EXPLAINER_VOICE_ENCODE_CJS: "packages/runtime/kits/explainer/voice-encode.cjs",
};
export const EXPLAINER_VOICE_GENERATED = "packages/runtime/src/cloud-app-kit-explainer-voice.generated.ts";
/** The data kits' engines, by the name the runtime holds each under (packages/runtime/src/cloud-app-kits.ts). */
export const KIT_ENGINE_SOURCES = {
	MODEL_ENGINE_JS: "packages/runtime/kits/model/engine.js",
	BOARD_ENGINE_JS: "packages/runtime/kits/board/engine.js",
	PATH_ENGINE_JS: "packages/runtime/kits/path/engine.js",
	OBJECT_ENGINE_JS: "packages/runtime/kits/object/engine.js",
};
/** What an agent is told of each data kit: what it draws and what its data file holds. */
export const KIT_GUIDE_SOURCES = {
	MODEL_KIT_GUIDE: "packages/runtime/kits/model/KIT.md",
	BOARD_KIT_GUIDE: "packages/runtime/kits/board/KIT.md",
	PATH_KIT_GUIDE: "packages/runtime/kits/path/KIT.md",
	OBJECT_KIT_GUIDE: "packages/runtime/kits/object/KIT.md",
};
export const KIT_ENGINES_GENERATED = "packages/runtime/src/cloud-app-kit-engines.generated.ts";

// A template literal, so a generated file reads line by line as its source does and the formatter leaves it alone.
const literal = (source) => `\`${source.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${")}\``;

/** The generated module's text for an engine's source. */
export function renderExplainerEngine(source) {
	return [
		`// Generated by scripts/generate-app-kits.mjs from ${EXPLAINER_ENGINE_SOURCE}. Do not edit: change that file,`,
		"// then run npm run generate:app-kits.",
		"",
		"/** The explainer kit's engine.js, as save_app writes it into an app's folder. */",
		`export const EXPLAINER_ENGINE_JS = ${literal(source)};`,
		"",
	].join("\n");
}

/** The generated module's text for the voice scripts: `sources` by constant name, in EXPLAINER_VOICE_SOURCES' order. */
export function renderExplainerVoice(sources) {
	return [
		"// Generated by scripts/generate-app-kits.mjs from packages/runtime/kits/explainer/voice-*.cjs. Do not edit: change",
		"// those files, then run npm run generate:app-kits.",
		...Object.entries(EXPLAINER_VOICE_SOURCES).flatMap(([name, path]) => [
			"",
			`/** ${path.slice(path.lastIndexOf("/") + 1)}, as the runtime runs it on a company machine. */`,
			`export const ${name} = ${literal(sources[name])};`,
		]),
		"",
	].join("\n");
}

/** The generated module's text for the data kits: each one's guide, then each one's engine; `sources` by constant
 * name, in KIT_GUIDE_SOURCES' and KIT_ENGINE_SOURCES' order. */
export function renderKitEngines(sources) {
	return [
		"// Generated by scripts/generate-app-kits.mjs from packages/runtime/kits/<kit>/KIT.md and engine.js. Do not edit:",
		"// change those files, then run npm run generate:app-kits.",
		...Object.entries(KIT_GUIDE_SOURCES).flatMap(([name, path]) => [
			"",
			`/** The ${path.split("/").at(-2)} kit's guide for agents, as save_app's schema carries it. */`,
			`export const ${name} = ${literal(sources[name])};`,
		]),
		...Object.entries(KIT_ENGINE_SOURCES).flatMap(([name, path]) => [
			"",
			`/** The ${path.split("/").at(-2)} kit's engine.js, as save_app writes it into an app's folder. */`,
			`export const ${name} = ${literal(sources[name])};`,
		]),
		"",
	].join("\n");
}

async function write(path, next) {
	const current = await readFile(join(root, path), "utf8").catch(() => null);
	if (next !== current) await writeFile(join(root, path), next);
	console.log(path);
}

async function main() {
	await write(EXPLAINER_ENGINE_GENERATED, renderExplainerEngine(await readFile(join(root, EXPLAINER_ENGINE_SOURCE), "utf8")));
	const sources = {};
	for (const [name, path] of Object.entries(EXPLAINER_VOICE_SOURCES)) sources[name] = await readFile(join(root, path), "utf8");
	await write(EXPLAINER_VOICE_GENERATED, renderExplainerVoice(sources));
	const engines = {};
	for (const [name, path] of Object.entries({ ...KIT_GUIDE_SOURCES, ...KIT_ENGINE_SOURCES }))
		engines[name] = await readFile(join(root, path), "utf8");
	await write(KIT_ENGINES_GENERATED, renderKitEngines(engines));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	main().catch((error) => {
		console.error(error instanceof Error ? error.message : String(error));
		process.exitCode = 1;
	});
}
