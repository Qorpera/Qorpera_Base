#!/usr/bin/env node
// Writes the files of the interface app kits (deploy/first-node/RUNTIME-INTERFACE-APPS.md §3a) into the runtime as
// text, so `save_app` can write them into an app's folder: packages/runtime/kits/explainer/engine.js becomes
// packages/runtime/src/cloud-app-kit-explainer-engine.generated.ts. Run it after changing a kit's file:
//   npm run generate:app-kits
// packages/runtime/test/cloud-app-kit-explainer.test.ts fails while the two differ.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const EXPLAINER_ENGINE_SOURCE = "packages/runtime/kits/explainer/engine.js";
export const EXPLAINER_ENGINE_GENERATED = "packages/runtime/src/cloud-app-kit-explainer-engine.generated.ts";

/** The generated module's text for an engine's source. */
export function renderExplainerEngine(source) {
	return [
		`// Generated by scripts/generate-app-kits.mjs from ${EXPLAINER_ENGINE_SOURCE}. Do not edit: change that file,`,
		"// then run npm run generate:app-kits.",
		"",
		"/** The explainer kit's engine.js, as save_app writes it into an app's folder. */",
		// A template literal, so the file reads line by line as the source does and the formatter leaves it alone.
		`export const EXPLAINER_ENGINE_JS = \`${source.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${")}\`;`,
		"",
	].join("\n");
}

async function main() {
	const next = renderExplainerEngine(await readFile(join(root, EXPLAINER_ENGINE_SOURCE), "utf8"));
	const path = join(root, EXPLAINER_ENGINE_GENERATED);
	const current = await readFile(path, "utf8").catch(() => null);
	if (next !== current) await writeFile(path, next);
	console.log(EXPLAINER_ENGINE_GENERATED);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	main().catch((error) => {
		console.error(error instanceof Error ? error.message : String(error));
		process.exitCode = 1;
	});
}
