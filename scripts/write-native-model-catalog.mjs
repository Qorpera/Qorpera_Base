#!/usr/bin/env node
// Writes packages/runtime/src/cloud-codex-model-catalog.generated.ts from what a live run's Codex saved, on stdin:
// {"client_version", "fetched_at", "models"} (deploy/first-node/native-codex/README.md, "Model catalog").
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

let input = "";
for await (const chunk of process.stdin) input += chunk;
const { client_version: version, fetched_at: fetchedAt, models } = JSON.parse(input);
if (typeof version !== "string" || typeof fetchedAt !== "string" || !Array.isArray(models) || models.length === 0)
	throw new Error("Expected client_version, fetched_at and models");
// In the quotes biome keeps for a string with this many double quotes.
const quoted = (text) => `'${text.replaceAll("\\", "\\\\").replaceAll("'", "\\'")}'`;
const lines = [
	"// Generated by scripts/write-native-model-catalog.mjs from a live run's models_cache.json. Do not edit.",
	`export const CLOUD_CODEX_MODEL_CATALOG_CLIENT_VERSION = ${JSON.stringify(version)};`,
	`export const CLOUD_CODEX_MODEL_CATALOG_CAPTURED_AT = ${JSON.stringify(`${fetchedAt.slice(0, 19)}Z`)};`,
	"/** The provider's catalog for that Codex version: one model's JSON per line, so a refresh shows which ones changed. */",
	"export const CLOUD_CODEX_MODEL_CATALOG_MODELS: readonly string[] = [",
	...models.map((model) => `\t${quoted(JSON.stringify(model))},`),
	"];",
	"",
];
const target = resolve(dirname(fileURLToPath(import.meta.url)), "../packages/runtime/src/cloud-codex-model-catalog.generated.ts");
writeFileSync(target, lines.join("\n"));
