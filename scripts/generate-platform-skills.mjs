#!/usr/bin/env node
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const PLATFORM_SKILLS_FOLDER = "packages/runtime/skills";
export const PLATFORM_SKILLS_GENERATED = "packages/runtime/src/cloud-platform-skills.generated.ts";

const literal = (source) => `\`${source.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${")}\``;

export function renderPlatformSkills(files) {
	return [
		`// Generated by scripts/generate-platform-skills.mjs from ${PLATFORM_SKILLS_FOLDER}/<name>/SKILL.md. Do not edit:`,
		"// change those files, then run node scripts/generate-platform-skills.mjs.",
		"",
		"/** The platform's skills, by name: each one's SKILL.md as it ships with the runtime. */",
		"export const PLATFORM_SKILL_FILES: Readonly<Record<string, string>> = {",
		...Object.keys(files)
			.sort()
			.map((name) => `\t"${name}": ${literal(files[name])},`),
		"};",
		"",
	].join("\n");
}

async function main() {
	const files = {};
	for (const entry of await readdir(join(root, PLATFORM_SKILLS_FOLDER), { withFileTypes: true })) {
		if (!entry.isDirectory()) continue;
		files[entry.name] = await readFile(join(root, PLATFORM_SKILLS_FOLDER, entry.name, "SKILL.md"), "utf8");
	}
	const next = renderPlatformSkills(files);
	const current = await readFile(join(root, PLATFORM_SKILLS_GENERATED), "utf8").catch(() => null);
	if (next !== current) await writeFile(join(root, PLATFORM_SKILLS_GENERATED), next);
	console.log(PLATFORM_SKILLS_GENERATED);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	main().catch((error) => {
		console.error(error instanceof Error ? error.message : String(error));
		process.exitCode = 1;
	});
}
